  id: string;
  name: string;
  /** 一覧で見出しをつけてまとめる時の名前（なければ「その他」） */
  group?: string;
  /** ボタンの title に出す説明 */
  note?: string;
  /** 一覧に絵を出す切り札（デッキに入っているカード名） */
  cover?: string;
  /** 切り札の公式カードID（絵を出すのに使う。なければ名前の頭文字を出す） */
  coverId?: string;
  /** parseDeckText で読める形のデッキリスト */
